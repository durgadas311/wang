// Assume starting (origin) point is LL corner of cell:
//	+----+
//	|    |
//	|    |
//	|    |
//	+----+
//     O
// Always return to origin at end of char.
//
// Original ROM layout:
//
//  9  8  7  6  5  4  3  2  1  0
//  S  ---Y---  y  ---X---  x  P
//
//	S = STOP (1=last entry for char)
//	Y = delta Y magnitude
//	y = delta Y sign (1 = pos)
//	X = delta X magnitude
//	x = delta X sign (1 = pos)
//	P = Pen (1 = down/draw)

#ifndef MAKE_STRUCT
#define ROM(s,p,x,y)	\
	((s << 9) | p | \
	(((y < 0 ? -y : y) & 7) << 6) | ((y < 0 ? 0 : 1) << 5) | \
	(((x < 0 ? -x : x) & 7) << 2) | ((x < 0 ? 0 : 1) << 1))
typedef uint16_t chrgen_t;
#else	// the old way, deprecated
#define ROM(s,p,x,y)	{(s << 7) | p, x, y}
struct chrgen_s {
	uint8_t pen;
	uint8_t x;
	uint8_t y;
};
typedef struct chrgen_s chrgen_t;
#endif

